import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const S = process.env.S
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []; page.on('pageerror', e => errors.push(e.message))
const from = 1700000000, to = 1701000000
const names = ['Ada Lovelace', 'grace.hopper', 'Linus']
const commits = Array.from({ length: 40 }, (_, c) => ({ hash: String(c), ts: from + c * (to - from) / 39, name: names[c % 3], email: 'x@example.com', files: Array.from({ length: c % 7 === 0 ? 24 : 3 }, (_, j) => ({ p: `src/area${c % 5}/f${(c + j) % 9}.js`, a: 5, d: 1 })) }))
const result = { repo: 'example/video', commits, stats: { from, to, commits: 40, authors: 3, loc: 1234, topAuthors: names.map(n => [n, commits.filter(c => c.name === n).length]) } }
await page.route('**/api/config', r => r.fulfill({ json: { defaultRepo: 'example/video', gitea: null } }))
await page.route('**/api/music', r => r.fulfill({ json: { tracks: [{ id: 'floating-cities', title: 'Floating Cities', mood: 'ambient' }, { id: 'cipher', title: 'Cipher', mood: 'tech' }] } }))
// Real playable audio catches pause/resume regressions that a 404 stub cannot.
const wav = Buffer.alloc(44 + 8000 * 2 * 45)
wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8)
wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22)
wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34)
wav.write('data', 36); wav.writeUInt32LE(wav.length - 44, 40)
await page.route('**/api/music/*/file', r => r.fulfill({ contentType: 'audio/wav', body: wav }))
await page.route('**/api/load', r => r.fulfill({ json: { job: 'test' } }))
await page.route('**/api/status/test', r => r.fulfill({ json: { status: 'done', result } }))
await page.goto('http://127.0.0.1:5173/viewer.html')
await page.getByRole('button', { name: 'Pause', exact: true }).click()
// play first: a second renderer must not inherit the viewer's per-commit geometry (regression: stack overflow)
await page.getByRole('button', { name: '4×', exact: true }).click(); await page.getByRole('button', { name: 'Play', exact: true }).click()
await page.waitForTimeout(3000); await page.getByRole('button', { name: 'Pause', exact: true }).click()
await page.getByRole('button', { name: /Video/ }).click()
const mode = page.locator('.video-mode')
await mode.waitFor()
await page.getByRole('combobox', { name: /Length/ }).selectOption('15')
await page.waitForTimeout(800)
assert.equal(await mode.getAttribute('data-phase'), 'intro')
await page.screenshot({ path: `${S}/video-intro.png` })
await page.waitForFunction(() => document.querySelector('.video-mode')?.dataset.phase === 'history', null, { timeout: 8000 })
await page.waitForTimeout(3000)
await page.screenshot({ path: `${S}/video-history.png` })
assert.ok(await page.locator('.video-mode audio').evaluate(a => a.volume > 0 && a.volume <= 0.30), 'music stays at the quieter level')
// music is changeable: select, next-track button, and the m key each switch the audio source
const src = () => page.evaluate(() => document.querySelector('.video-mode audio')?.getAttribute('src') ?? null)
await page.getByRole('combobox', { name: 'Music track' }).focus(); await page.getByRole('combobox', { name: 'Music track' }).selectOption('cipher'); await page.waitForTimeout(200)
assert.match(await src(), /cipher/)
await page.getByRole('button', { name: 'Next track' }).click(); await page.waitForTimeout(200)
assert.equal(await src(), null, 'after the last track comes "no music"')
await mode.focus(); await page.keyboard.press('m'); await page.waitForTimeout(200)
assert.match(await src(), /floating-cities/)
assert.match(await page.locator('.video-toast').innerText(), /Floating Cities/)
// Pause preserves music position, and clicking the canvas really resumes.
await page.waitForFunction(() => document.querySelector('.video-mode audio')?.currentTime > 0.8)
await mode.focus(); await page.keyboard.press('Space'); await page.waitForTimeout(250)
await page.locator('.video-controls').getByRole('button', { name: 'Play', exact: true }).waitFor()
const pausedAt = await page.locator('.video-mode audio').evaluate(a => a.currentTime)
await page.locator('.video-canvas').click({ position: { x: 100, y: 100 } })
await page.waitForTimeout(350)
assert.ok(await page.locator('.video-mode audio').evaluate((a, t) => !a.paused && a.currentTime >= t && a.currentTime < t + 1, pausedAt), 'resume does not restart the music')
const volume = page.getByRole('slider', { name: 'Music volume' })
await volume.fill('12'); await page.waitForTimeout(1200)
assert.ok(await page.locator('.video-mode audio').evaluate(a => a.volume > 0.11 && a.volume < 0.13), 'volume adjusts smoothly')
await volume.focus(); await page.keyboard.press('ArrowRight')
assert.equal(await volume.inputValue(), '13', 'native slider keyboard handling works')
await page.getByRole('checkbox', { name: 'effects' }).uncheck()
const position = page.getByRole('slider', { name: 'Playback position' })
await mode.focus(); await page.keyboard.press('Space')
await position.fill('8'); await page.waitForTimeout(200)
assert.equal(await position.inputValue(), '8', 'seek works while paused')
await mode.focus(); await page.keyboard.press('ArrowLeft'); await page.waitForTimeout(200)
assert.equal(await position.inputValue(), '3', 'keyboard seeks five seconds')
await volume.focus(); await page.mouse.move(0, 0); await page.waitForTimeout(2800)
assert.equal(await page.locator('.video-controls').evaluate(el => getComputedStyle(el).opacity), '1', 'focused controls remain visible')
await page.screenshot({ path: `${S}/video-controls.png` })
await position.fill('21'); await page.waitForTimeout(200)
await page.screenshot({ path: `${S}/video-outro.png` })
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
assert.equal(await page.locator('.video-mode').count(), 0, 'esc exits')
await page.setViewportSize({ width: 390, height: 844 })
await page.getByRole('button', { name: /Video/ }).click()
await page.waitForTimeout(300)
const box = await page.locator('.video-controls').boundingBox()
assert.ok(box.x >= 0 && box.x + box.width <= 390, 'controls fit mobile width')
await page.screenshot({ path: `${S}/video-mobile.png` })
assert.equal(await volume.inputValue(), '13', 'volume is remembered')
assert.equal(await page.getByRole('checkbox', { name: 'effects' }).isChecked(), false, 'effects preference is remembered')
await page.keyboard.press('Escape')
assert.deepEqual(errors, [])
console.log('video mode check ok')
// a video link opens straight into fullscreen playback, and video mode hands out such links
await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
await page.goto('http://127.0.0.1:5173/viewer.html?repo=example/video&video=1&clock=0')
await page.locator('.video-mode').waitFor({ timeout: 30000 })
await page.getByRole('button', { name: 'Copy video link' }).click()
const copied = await page.evaluate(() => navigator.clipboard.readText())
const link = new URL(copied)
assert.equal(link.searchParams.get('video'), '1'); assert.equal(link.searchParams.get('repo'), 'example/video'); assert.equal(link.searchParams.get('clock'), '0')
assert.match(await page.locator('.video-toast').innerText(), /Video link copied/)
await page.keyboard.press('Escape')
assert.equal(await page.locator('.video-mode').count(), 0)
assert.deepEqual(errors, [])
console.log('video link ok')
await browser.close()
