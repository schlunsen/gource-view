import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []; page.on('pageerror', e => errors.push(e.message))
const from = 1700000000, to = from + 100000
const result = (name, ref = 'main') => ({ description: 'A small application for organizing team notes.', repo: name, ref, defaultRef: 'main', refs: ['main', 'dev'], commits: Array.from({ length: 20 }, (_, i) => ({ hash: String(i), ts: from + i * (to - from) / 19, name: i % 2 ? 'Ada' : 'Grace', files: [{ p: `src/area${i % 4}/file${i}.js`, a: 2, d: 1 }] })), stats: { from, to, commits: 20, authors: 2, loc: 20, topAuthors: [['Ada', 10], ['Grace', 10]] } })
let mode = 'done'
const loads = []
await page.route('**/api/config', r => r.fulfill({ json: { defaultRepo: 'example/first' } }))
await page.route('**/api/music', r => r.fulfill({ json: { tracks: [] } }))
await page.route('**/api/load', r => { loads.push(r.request().postDataJSON()); return r.fulfill({ json: { job: String(loads.length) } }) })
await page.route('**/api/status/*', r => {
  const n = +r.request().url().split('/').pop() - 1
  if (mode === 'offline') return r.abort('failed')
  return r.fulfill({ json: mode === 'done' ? { status: 'done', result: result(loads[n].repo, loads[n].options.ref) } : mode === 'error' ? { status: 'error', error: 'Repository is unavailable' } : { status: 'working', progress: { pct: 25, detail: 'Reading history…' } } })
})
await page.goto('http://127.0.0.1:5173/')
await page.getByRole('button', { name: 'Pause', exact: true }).click()
assert.equal(await page.locator('.repo-description').innerText(), 'A small application for organizing team notes.')
await page.getByRole('button', { name: 'stats', exact: true }).click()
assert.equal(await page.locator('.repo-description').isVisible(), false, 'description follows stats toggle')
await page.getByRole('button', { name: 'stats', exact: true }).click()
await page.getByRole('button', { name: 'Privacy off', exact: true }).click()
assert.equal(await page.locator('.repo-description').count(), 0, 'privacy hides project descriptions')
await page.getByRole('button', { name: 'Names hidden', exact: true }).click()
await page.getByRole('button', { name: 'Names + people hidden', exact: true }).click()
assert.equal(loads[0].options.maxCommits, 300, 'fresh visits default to a small history')
await page.getByRole('combobox', { name: 'Branch' }).selectOption('dev')
await page.waitForFunction(() => document.querySelector('select[aria-label="Branch"]')?.value === 'dev')
await page.locator('.repo-discovery summary').click()
await page.getByRole('searchbox', { name: 'Search example repositories' }).fill('Python')
assert.equal(await page.getByRole('navigation', { name: 'Suggested repos' }).getByRole('button').count(), 1)
await page.screenshot({ path: `${process.env.S}/app-discovery.png` })
await page.getByRole('button', { name: 'pallets/flask', exact: true }).click()
await page.waitForFunction(() => document.querySelector('.scene-heading h2')?.textContent === 'flask')
assert.equal(loads.at(-1).options.ref, undefined, 'new repositories do not inherit the previous branch')
const submit = async name => { await page.getByLabel('Repository', { exact: true }).fill(name); await page.getByRole('button', { name: 'Load', exact: true }).click() }
mode = 'working'; await submit('example/slow')
await page.getByRole('button', { name: 'Stop waiting' }).click()
assert.equal(await page.locator('.scene-heading h2').innerText(), 'flask', 'cancel retains the last visualization')
mode = 'error'; await submit('example/broken')
await page.getByRole('alert').waitFor()
await page.screenshot({ path: `${process.env.S}/app-recovery.png` })
await page.getByRole('button', { name: 'Back to viewer' }).click()
assert.equal(await page.getByLabel('Repository', { exact: true }).inputValue(), 'pallets/flask')
mode = 'offline'; await submit('example/reconnect')
await page.getByRole('alert').waitFor({ timeout: 10000 })
assert.match(await page.getByRole('alert').innerText(), /Connection interrupted/)
mode = 'done'; await page.getByRole('button', { name: 'Try again' }).click()
await page.waitForFunction(() => document.querySelector('.scene-heading h2')?.textContent === 'reconnect')
await page.getByRole('button', { name: 'Pause', exact: true }).click()
// The URL describes the loaded history, not a commit limit selected for a future load.
await page.getByLabel('Max commits to load').selectOption('0')
await page.waitForTimeout(100)
assert.equal(new URL(page.url()).searchParams.get('max'), '300')
await page.screenshot({ path: `${process.env.S}/app-desktop.png` })
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(200)
const toolbar = await page.locator('.view-tools').boundingBox()
assert.ok(toolbar.x >= 0 && toolbar.x + toolbar.width <= 390, 'all view tools fit mobile width')
await page.screenshot({ path: `${process.env.S}/app-mobile.png` })
await page.locator('.repo-discovery summary').click()
assert.equal(await page.getByRole('searchbox', { name: 'Search example repositories' }).isVisible(), true)
assert.deepEqual(errors, [])
console.log('app discovery, loading recovery, branch isolation and mobile checks ok')
await browser.close()
